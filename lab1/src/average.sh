#!/bin/bash

# $# содержит общее количество переданных аргументов
count=$#

# Если аргументов нет, выводим ошибку и выходим
if [ $count -eq 0 ]; then
    echo "Количество аргументов: 0"
    echo "Среднее арифметическое: 0"
    exit 0
fi

sum=0

# Цикл по всем переданным аргументам ($@)
for num in "$@"; do
    sum=$((sum + num))
done

# Вычисляем среднее с плавающей точкой (до 2 знаков после запятой) через bc
average=$(echo "scale=2; $sum / $count" | bc)

echo "Количество чисел: $count"
echo "Среднее арифметическое: $average"

